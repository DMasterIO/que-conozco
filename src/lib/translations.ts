export const STORAGE_KEY = 'que-conozco-lang'

export function detectLang(): Lang {
  if (typeof navigator !== 'undefined' && navigator.language) {
    return navigator.language.toLowerCase().startsWith('en') ? 'en' : 'es'
  }
  return 'es'
}

