// Writes src/data/microstates.ts: a [lat, lng] anchor for every country that has localities but
// is too small for the 110m world atlas, so the map can still show a clickable dot for it.
//
// Run with: node scripts/gen-microstates.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const atlas = require('world-atlas/countries-110m.json')
const countries = require('world-countries')
const index = JSON.parse(readFileSync('public/data/country-index.json', 'utf8'))

const onMap = new Set(atlas.objects.countries.geometries.map((g) => String(g.id)))
const out = {}
for (const c of countries) {
  if (!c.ccn3 || !index[c.cca2]?.length || onMap.has(c.ccn3)) continue
  if (!c.latlng?.length) continue
  out[c.cca2] = [Number(c.latlng[0].toFixed(2)), Number(c.latlng[1].toFixed(2))]
}

writeFileSync(
  'src/data/microstates.ts',
  `// Auto-generated by scripts/gen-microstates.mjs. cca2 -> [lat, lng] of countries missing from the 110m atlas.\nexport const MICROSTATES: Record<string, [number, number]> = ${JSON.stringify(out)}\n`,
)
console.log(`${Object.keys(out).length} microstates`)
