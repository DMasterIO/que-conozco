// Collects the license texts of the third-party code shipped to browsers (production
// dependencies, their transitive dependencies, and the Workbox modules bundled into the
// service worker) into public/third-party-licenses.txt. MIT/ISC/Apache require the notice to
// travel with the code, and bundlers strip the comments that normally carry it.
//
// Runs automatically before `npm run build`.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const pkgDir = (name) => resolve(root, 'node_modules', name)
const readJson = (file) => JSON.parse(readFileSync(file, 'utf8'))

// Bundled into sw.js by vite-plugin-pwa (they are dependencies of a dev tool, not of the app).
const EXTRA = ['workbox-window', 'workbox-core', 'workbox-routing', 'workbox-strategies', 'workbox-precaching', 'workbox-expiration', 'workbox-cacheable-response']

const seen = new Map()
function visit(name) {
  if (seen.has(name) || !existsSync(pkgDir(name))) return
  const pkg = readJson(resolve(pkgDir(name), 'package.json'))
  seen.set(name, pkg)
  for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep)
}
for (const dep of Object.keys(readJson(resolve(root, 'package.json')).dependencies)) visit(dep)
for (const name of EXTRA) visit(name)

function licenseText(name) {
  const dir = pkgDir(name)
  const file = readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.|$)/i.test(f))
  return file ? readFileSync(resolve(dir, file), 'utf8').trim() : null
}

const parts = [
  'Third-party software notices for ¿Qué conozco? (auto-generated by scripts/gen-licenses.mjs)',
  '',
]
for (const [name, pkg] of [...seen].sort(([a], [b]) => a.localeCompare(b))) {
  const license = typeof pkg.license === 'string' ? pkg.license : JSON.stringify(pkg.license ?? pkg.licenses)
  parts.push('='.repeat(72), `${name}@${pkg.version} — ${license}`, pkg.homepage ?? '', '')
  parts.push(licenseText(name) ?? `(no license file shipped; declared license: ${license})`, '')
}
writeFileSync(resolve(root, 'public/third-party-licenses.txt'), parts.join('\n'))
console.log(`third-party-licenses.txt: ${seen.size} packages`)
